from decimal import Decimal

# ============================================================
# Tier A — вхідний фільтр ліквідності (crypto_screening/tier_a.py)
# ============================================================
# Жодна монета не розглядається далі (LONG/SHORT/WATCH), поки не
# пройде ВСІ чотири критерії нижче одночасно.

# Мінімальний агрегований $-обсяг торгів за добу (сума по 3 біржах,
# де монета присутня). Та сама планка, що Tier A для акцій S&P 500.
MIN_QUOTE_VOLUME_24H = Decimal("10000000")  # $10 млн/добу

# Мінімальний агрегований Open Interest (сума по біржах, де є дані;
# Binance OI додається окремим запитом лише для прикордонних
# випадків — docs/decisions.md, 2026-10-02).
MIN_OPEN_INTEREST_USD = Decimal("5000000")  # $5 млн

# Мінімальна кількість бірж (з 3: Binance/Bybit/OKX), де монета
# торгується одночасно — безкоштовний proxy "легітимності" лістингу,
# не фінансова оцінка.
# Знижено з 2 до 1 (2026-10-03, живий кейс користувача: AINUSDT —
# $180М обсягу/24г, ~$20М OI, лістинг з 2025-07-10, усе далеко вище
# порогів — але торгується ЛИШЕ на Binance, тож відсіювався Tier A
# попри очевидну ліквідність). Відсіювання через "лише 1 біржа"
# більше не застосовується самостійно — обсяг/OI лишаються справжнім
# гейтом ліквідності, кількість бірж більше НЕ додатковий бар'єр понад
# них.
MIN_EXCHANGE_COUNT = 1

# Мінімальний вік лістингу в днях (найстаріший onboard_date серед
# бірж, де монета присутня) — відсіює щойно-лістовані/маніпульовані
# контракти.
MIN_LISTING_AGE_DAYS = 30


# ============================================================
# LONG — продовження тренду (crypto_screening/long_screen.py)
# ============================================================
# Усі чотири критерії нижче мають пройти одночасно.
# ⚠️ Відомий пробіл методології (живий кейс, 2026-10-03): жодної
# перевірки, НАСКІЛЬКИ актив уже зріс від початку руху — монета, що
# зросла в десятки разів, формально проходить, якщо поточний RSI
# опинився в "здоровій" зоні. Залишено без змін за прямою вказівкою
# користувача ("Long поки лишай") — калібрування відкладено.

# RSI "здорової" бичачої зони — нижня і верхня межа. Нижче 50 —
# слабкий імпульс, вище 75 — уже перегрітий (ближче до розвороту, не
# до продовження).
RSI_HEALTHY_MIN = 50.0
RSI_HEALTHY_MAX = 75.0

# Максимальний funding rate (частка за період) для лонгу — вище
# вважається "перегрітим"/задорогим для відкриття нового лонгу.
MAX_FUNDING_RATE_LONG = Decimal("0.0005")  # 0.05% за період

# Вікно (днів), за яке рахується зміна Open Interest для LONG —
# "OI росте разом із ціною" (довший горизонт, той самий, що тренд).
OI_WINDOW_DAYS_LONG = 7


# ============================================================
# SHORT/WATCH — виснаження/розворот після пампу
# (crypto_screening/short_watch_screen.py)
# ============================================================

# Мінімальний памп за 24г (МАКСИМУМ серед бірж, не середнє), щоб
# монета взагалі розглядалась як кандидат на SHORT/WATCH — і заводилась
# у crypto_screening_candidates для погодинного моніторингу
# (monitor_candidates.py), незалежно від того, чи підтвердяться далі
# SHORT/WATCH-критерії.
PUMP_THRESHOLD_PCT = 30.0

# Критичний поріг негативного funding rate (частка за період) —
# ПЕРШИЙ і пріоритетний критерій, перевіряється ДО решти: памп +
# funding ≤ цього порогу → WATCH (НЕ SHORT), бо натовп шортистів уже
# в позиції — новий шорт проти перевантаженого натовпу ризикує
# short squeeze.
# Пом'якшено 2026-10-03 (рішення користувача, живий кейс SANDUSDT:
# памп 75%, funding −0.85% — цікавий кандидат, але не долетів до
# початкового порогу −2%). Було Decimal("-0.02").
CRITICAL_NEGATIVE_FUNDING = Decimal("-0.01")  # -1% за період

# RSI "перегрітості" для SHORT — разом з OI/обсягом нижче, УСІ ТРИ
# мають підтвердитись одночасно (крім WATCH-гейту вище, який спрацьовує
# окремо й раніше).
RSI_OVERBOUGHT = 70.0

# Мінімальний сплеск обсягу (%, від середнього за VOLUME_LOOKBACK_DAYS
# нижче) для підтвердження, що розворот реальний, не шум.
MIN_VOLUME_SPIKE_PCT = 20.0

# Різке падіння ціни за ОСТАННЮ ГОДИНУ (%) — АЛЬТЕРНАТИВНЕ (не єдине)
# підтвердження розвороту, поруч із MIN_VOLUME_SPIKE_PCT вище. Додано
# 2026-10-03 (живий кейс користувача: MAGMAUSDT не підхоплений на
# SHORT вчасно) — pump_pct/volume_spike_pct самі рахуються з
# 24-ГОДИННИХ rolling-показників бірж (price24hPcnt/priceChangePercent),
# тож різкий розворот у межах ОДНІЄЇ години розмивається добовим вікном
# і може лишатись непоміченим кілька годин поспіль, доки 24h-метрики
# не "наздоженуть". Застосовується ЛИШЕ в monitor_candidates.py
# (погодинний моніторинг уже активних кандидатів) — run_screening.py
# (перша детекція) не має "минулої години" для порівняння, там цей
# параметр завжди None (не впливає на початкову детекцію).
HOURLY_PRICE_DROP_PCT = -5.0  # -5% за годину

# Вікно (днів) для зміни OI "ПІСЛЯ пампу" (SHORT) — короткий, свіжий
# відкат, на відміну від довшого LONG-вікна вище.
OI_WINDOW_DAYS_SHORT = 2


# ============================================================
# Загальне (crypto_screening/run_screening.py)
# ============================================================

# Скільки днів історії обсягу читати з БД для розрахунку сплеску
# (використовується й WATCH/SHORT, і сам тригер OI_WINDOW_DAYS_SHORT
# вище не залежить від цього окремо).
VOLUME_LOOKBACK_DAYS = 7

# Скільки останніх денних свічок (Binance klines) тягнути для
# RSI/тренду/backtest на кожен Tier A-символ.
KLINES_LIMIT = 30

# Період RSI (свічок) — стандартний Wilder's smoothing. Той самий
# період використовується і для денного (первинний скан/LONG), і для
# коротшого ТФ моніторингу нижче — лише розмір СВІЧКИ різний, не
# кількість періодів.
RSI_PERIOD = 14


# ============================================================
# Погодинний моніторинг УЖЕ активних кандидатів
# (monitor_candidates.py) — ІНШИЙ (коротший) ТФ, ніж первинний
# скан/LONG вище
# ============================================================
# Рішення користувача, 2026-10-03: "денний ТФ підходить для глобальних
# висновків, а сам моніторинг уже відібраних активів потрібно
# використовувати дані за менший ТФ" — RSI/обсяг рахуються з
# ІНШИХ (коротших) Binance-свічок під час моніторингу, не з тих 30
# денних, що й первинний скан (KLINES_LIMIT/RSI_PERIOD вище лишаються
# для первинного скану без змін). OI (погодинна дельта "з минулого
# разу") і нова погодинна %-зміна ціни вже на коротшому ТФ (~1г,
# прив'язано до частоти самої джоби) — без змін тут.

# Інтервал Binance klines для RSI/сплеску обсягу ПІД ЧАС моніторингу —
# 4г: стійкіший сигнал, ніж 1г (менше шуму), усе ще в ~6 разів
# швидший за денний.
MONITORING_KLINE_INTERVAL = "4h"

# Скільки 4г-свічок тягнути — 42 свічки ≈ 7 днів (той самий горизонт,
# що VOLUME_LOOKBACK_DAYS вище, просто дрібнішими кроками): 1 найновіша
# свічка — "сплеск", решта 41 — базова лінія для порівняння.
MONITORING_KLINES_LIMIT = 42
