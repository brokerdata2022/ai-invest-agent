"""
Усі налаштування списку активів для торгів — ОДИН файл для ручного
редагування в продакшені (той самий принцип, що
`analysis/crypto_screening/config.py` і `orchestration/schedule.py`;
рішення користувача, вже озвучене двічі: "я не буду в продакшні шукати
де задані дані в коді, потрібен окремий файл з коментарями та
поясненнями"). Жоден інший файл модуля не визначає ці значення сам —
усі імпортують звідси.

Дизайн і обґрунтування кожного рішення — `docs/trading-list.md`.

⚠️ Усі числа нижче — ПОЧАТКОВІ ОРІЄНТИРИ для калібрування на живих
даних, не остаточна "правильна" формула. Саме тому внески компонентів
зберігаються в `trading_list` окремо: без них незрозуміло, що саме
підняло актив у топ, і калібрувати ваги навмання.
"""

from decimal import Decimal

# ============================================================
# ГОРИЗОНТ
# ============================================================
# 'medium' — дні-тижні (рішення користувача 2026-10-04: починаємо з
# середньостроку). 'intraday' — закладене розширення, НЕ реалізоване:
# інший профіль ваг нижче + додатковий гейт "ринок відкритий у цю
# сесію" (docs/trading-list.md, розділ "Розширення").
HORIZON = "medium"


# ============================================================
# ВАГИ КОМПОНЕНТІВ СКОРУ
# ============================================================
# Фінальний скор = catalyst*W_CATALYST + trend*W_TREND + quality*W_QUALITY,
# кожен компонент нормований у [0, 1]. Суму ваг тримаємо = 1, щоб скор
# лишався в [0, 1] і поріг нижче читався як відсоток.
#
# Чому саме такий розподіл для СЕРЕДНЬОСТРОКУ:
# - каталізатор найважливіший, бо саме він відрізняє "є що торгувати"
#   від "хороша компанія" (без нього список = 215 рядків скринінгу);
# - тренд майже так само важливий — для свінгу вхід проти тренду
#   найдорожча помилка;
# - фундаментал важить, але найменше: він повільний і вже
#   використаний як вхідний фільтр універсуму (Tier A/B/C).
# Для 'intraday' профіль інший: quality → 0, тренд/рух домінують.
W_CATALYST = Decimal("0.45")
W_TREND = Decimal("0.35")
W_QUALITY = Decimal("0.20")


# ============================================================
# ПОРІГ І РОЗМІР СПИСКУ
# ============================================================
# Мінімальний фінальний скор, щоб актив узагалі потрапив у список.
# Свідомо не 0: список без порога — це ранжований універсум, а не
# фільтр.
MIN_SCORE = Decimal("0.35")

# Скільки рядків у фінальному списку. Список має бути ДІЄЗДАТНИМ —
# 5-10 позицій, які реально можна переглянути перед сесією, не 50.
MAX_ITEMS = 10

# Скільки з MAX_ITEMS зарезервовано для watchlist-активів (вибір
# користувача має пріоритет). Той самий механізм, що вже затверджений
# для новин — `reporting/news_notify.py:WATCHLIST_MIN_SLOTS`.
# ⚠️ Слот НЕ заповнюється насильно: якщо watchlist-актив не пройшов
# MIN_SCORE (немає ні релізу, ні новини, ні руху), слот лишається
# порожнім. Інакше список вироджується у /notify_watchlist, який уже
# існує.
WATCHLIST_RESERVED_SLOTS = 3

# Бонус до скору watchlist-активу (додається ПІСЛЯ зважування, перед
# порогом) — пріоритет вибору користувача, але не безумовний пропуск.
WATCHLIST_SCORE_BONUS = Decimal("0.10")


# ============================================================
# КАТАЛІЗАТОР — вікна й пороги
# ============================================================
# Скільки днів наперед дивимось на ЗАПЛАНОВАНІ релізи (release_log
# 'pending'). Для середньостроку вікно днів, не хвилин: позиція
# відкривається заздалегідь під очікувану подію.
CATALYST_UPCOMING_DAYS = 5

# Скільки днів назад дивимось на ВИЙШЛІ релізи (release_log
# 'processed' + expectation_synthesis) — реакція на сюрприз живе
# кілька днів, не кілька хвилин.
CATALYST_RECENT_DAYS = 3

# Мінімальна кількість незалежних джерел у новинному кластері
# (news_consolidated.source_count), щоб новина вважалась
# каталізатором. Механічна важливість, не LLM-confidence — рішення
# 2026-09-28 (docs/decisions.md): source_count замінив confidence як
# головний критерій.
MIN_NEWS_SOURCE_COUNT = 3

# Скільки годин назад дивимось на новини. 48г — те саме вікно, що
# зберігання raw_news (RETENTION_HOURS), глибше дані не живуть.
CATALYST_NEWS_HOURS = 48

# Мінімальний confidence LLM-синтезу ціна↔новини (news_synthesis), щоб
# він дав внесок у каталізатор.
MIN_SYNTHESIS_CONFIDENCE = Decimal("0.6")

# Внески окремих типів каталізатора в компонентний скор (нормується до
# [0,1] діленням на максимум можливої суми). Реліз високого впливу
# важить більше за новину, бо має відому ДАТУ й ЧАС.
CATALYST_WEIGHT_RELEASE_HIGH = Decimal("1.0")
CATALYST_WEIGHT_RELEASE_MEDIUM = Decimal("0.6")
CATALYST_WEIGHT_RELEASE_LOW = Decimal("0.2")
CATALYST_WEIGHT_NEWS = Decimal("0.7")
CATALYST_WEIGHT_SYNTHESIS = Decimal("0.6")
CATALYST_WEIGHT_FORECAST = Decimal("0.5")


# ============================================================
# НАШ ВЛАСНИЙ ПРОГНОЗ як каталізатор
# ============================================================
# Показники, прогноз яких ДОЗВОЛЕНО використовувати в торговому скорі.
# Тільки ті, де живий backtest показав перевагу над naive-базовою
# лінією (PLAN.md Фаза 2, таблиця 19 показників, 2026-10-04).
#
# КРИТИЧНО: `treasury_10y` (−13.6%), `treasury_2y` (−12.0%),
