# ============================================================
# ТРЕНД (шар торгуємості для акцій і watchlist)
# ============================================================
# Крипта свій тренд уже має (RSI/OI/funding,
# crypto_screening/config.py) — ці вікна для акцій і watchlist, де
# жодного шару торгуємості не було взагалі.
#
# Два вікна: коротке показує поточний імпульс, довше — чи він
# узгоджений із ширшим рухом. Узгоджені вікна дають сильніший сигнал,
# ніж будь-яке окремо.
TREND_SHORT_DAYS = 20
TREND_LONG_DAYS = 60

# %-зміна за TREND_SHORT_DAYS, від якої тренд вважається вираженим
