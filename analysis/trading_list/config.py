TREND_MIN_CHANGE_PCT = Decimal("3.0")

# %-зміна, на якій внесок тренду вважається максимальним (1.0) —
# усе вище не додає скору, щоб уже сильно вирослий актив не домінував
# у списку автоматично (той самий відомий пробіл, що в LONG-скрині
# крипти, docs/decisions.md 2026-10-03).
TREND_SATURATION_PCT = Decimal("15.0")

# Мінімум денних точок, щоб тренд узагалі рахувався. Без цього
